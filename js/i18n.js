// i18n Class
class I18n {
    constructor() {
        this.currentLang = this.getSavedLang() || 'uz';
        this.init();
    }

    getSavedLang() {
        const saved = localStorage.getItem('nikmt_lang');
        if (saved && ['uz', 'ru', 'en'].includes(saved)) {
            return saved;
        }
        // Check browser language
        const browserLang = navigator.language.slice(0, 2);
        if (['uz', 'ru', 'en'].includes(browserLang)) {
            return browserLang;
        }
        return null;
    }

    saveLang(lang) {
        localStorage.setItem('nikmt_lang', lang);
    }

    init() {
        this.translatePage();
        this.updateLangButtons();
        this.updateHtmlLang();
    }

    setLang(lang) {
        if (!translations[lang]) return;
        this.currentLang = lang;
        this.saveLang(lang);
        this.translatePage();
        this.updateLangButtons();
        this.updateHtmlLang();
    }

    updateHtmlLang() {
        document.documentElement.lang = this.currentLang;
    }

    updateLangButtons() {
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === this.currentLang);
        });
    }

    getNestedTranslation(key) {
        const keys = key.split('.');
        let value = translations[this.currentLang];
        for (const k of keys) {
            if (value && typeof value === 'object') {
                value = value[k];
            } else {
                return null;
            }
        }
        return value;
    }

    translatePage() {
        // Translate text content
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.getNestedTranslation(key);
            if (translation) {
                el.textContent = translation;
            }
        });

        // Translate placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = this.getNestedTranslation(key);
            if (translation) {
                el.placeholder = translation;
            }
        });

        // Update meta tags
        const metaTitle = this.getNestedTranslation('meta.title');
        const metaDesc = this.getNestedTranslation('meta.description');
        const metaKeywords = this.getNestedTranslation('meta.keywords');

        if (metaTitle) {
            document.title = metaTitle;
            document.querySelector('meta[property="og:title"]')?.setAttribute('content', metaTitle);
            document.querySelector('meta[property="twitter:title"]')?.setAttribute('content', metaTitle);
        }
        if (metaDesc) {
            document.querySelector('meta[name="description"]')?.setAttribute('content', metaDesc);
            document.querySelector('meta[property="og:description"]')?.setAttribute('content', metaDesc);
            document.querySelector('meta[property="twitter:description"]')?.setAttribute('content', metaDesc);
        }
        if (metaKeywords) {
            document.querySelector('meta[name="keywords"]')?.setAttribute('content', metaKeywords);
        }
    }
}

// Initialize i18n
const i18n = new I18n();

// Export for use in other files
window.i18n = i18n;
